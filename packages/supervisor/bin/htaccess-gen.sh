#!/usr/bin/env bash
# htaccess-gen.sh <host> <port> [--full]
# Emits the .htaccess that reverse-proxies a subdomain to the project's
# loopback port. Drop the output into the subdomain's document root, e.g.:
#   htaccess-gen.sh acme.example.com 18000 > ~/public_html/acme/.htaccess
#
# Default (selective): /api/* and /_/* (PocketBase API + admin UI) go to the
# binary; anything else can be served as static files from the document root.
# --full: every request goes to the backend.
set -euo pipefail

HOST="${1:?usage: htaccess-gen.sh <host> <port> [--full]}"
PORT="${2:?usage: htaccess-gen.sh <host> <port> [--full]}"
MODE="${3:-selective}"

[[ "$PORT" =~ ^[0-9]+$ ]] && [ "$PORT" -ge 1 ] && [ "$PORT" -le 65535 ] || {
  echo "error: bad port '$PORT'" >&2
  exit 1
}
# Escape dots so the host matches literally in the RewriteCond regex.
ESCAPED_HOST="${HOST//./\\.}"

cat <<EOF
# Generated by baas supervisor htaccess-gen.sh — $HOST -> 127.0.0.1:$PORT
# Place in the subdomain document root (e.g. ~/public_html/<sub>/.htaccess).
# Requires mod_proxy + mod_rewrite with the [P] flag allowed.
RewriteEngine On
RewriteCond %{HTTP_HOST} ^${ESCAPED_HOST}$ [NC]
EOF

if [ "$MODE" = "--full" ]; then
  cat <<EOF
# Full proxy: every request goes to the backend.
RewriteRule ^(.*)$ http://127.0.0.1:$PORT/\$1 [P,L,QSA]
EOF
else
  cat <<EOF
# Selective proxy: API + admin UI go to the binary; static marketing pages
# can live in the document root alongside this file.
RewriteCond %{REQUEST_URI} ^/api/ [OR]
RewriteCond %{REQUEST_URI} ^/_/
RewriteRule ^(.*)$ http://127.0.0.1:$PORT/\$1 [P,L,QSA]
EOF
fi

cat <<'EOF'
# --- Realtime note -----------------------------------------------------------
# PocketBase realtime uses Server-Sent Events over plain HTTP, which survives
# this proxy. True WebSockets need mod_proxy_wstunnel — many shared hosts
# disable it. Verify in preflight; degrade to polling if absent.
#
# --- Fallback ----------------------------------------------------------------
# If the host disables the [P] flag, the fallbacks in order are:
#   1. cPanel's Node.js app selector for the app itself
#   2. a tiny PHP reverse-proxy shim (functional, slower)
# Both are signals to prefer the reseller tier, where you control the package.
EOF
